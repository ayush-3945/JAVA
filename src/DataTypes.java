public class DataTypes {
    static void main(){

        // Numaric DataTypes : short , byte , long

        byte num1 = 127; // range is -127 to +127
        System.out.println(num1);
        short num2 = 32576; // range is -32768 to +32768
        System.out.println(num2);


        //Floating point : float , double

        float num3 = 3.14f;
        System.out.println(num3);
        double num4 = 3.147574747238474328;
        System.out.println(num4);

        //Other Datatype : char boolean

        boolean eligileToVote = true;
        System.out.println(eligileToVote);

        char FirstCharacter = 'a'; //all values in single coat...
        System.out.println(FirstCharacter);

        // Ascii Values
//        a = 97;   A = 65
//        b = 98;   B = 66
//        c = 99;

    }
}
